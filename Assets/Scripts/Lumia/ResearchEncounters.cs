        public static EventDef Event(string id) => Events.Find(x => x.id == id);
        public static EventDef EventForSubject(string subjectId) => Event(EventPrefix + subjectId);
        public static string SubjectForEvent(string eventId)
        {
            if (string.IsNullOrEmpty(eventId) || !eventId.StartsWith(EventPrefix, StringComparison.Ordinal)) return null;
            return Event(eventId) == null ? null : eventId.Substring(EventPrefix.Length);
        }
        public static string ReportText(string subjectId) => subjectId != null && Reports.TryGetValue(subjectId, out var text) ? text : "";

