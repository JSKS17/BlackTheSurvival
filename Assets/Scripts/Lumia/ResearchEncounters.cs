        static void E(string subjectId, string title, string story, string report, params EventOption[] options)
        {
            var subject = GameDatabase.Character(subjectId);
            if (subject == null) throw new InvalidOperationException("Unknown research subject: " + subjectId);
            if (Reports.ContainsKey(subjectId)) throw new InvalidOperationException("Duplicate research subject: " + subjectId);
            Reports.Add(subjectId, report);
            Events.Add(new EventDef { id = EventPrefix + subjectId, owner = subject.name, title = title, story = story, options = options });
        }

