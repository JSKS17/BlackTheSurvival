        static void S(List<EventDef> events, Dictionary<string, string> reports, string subjectId,
            string title, string story, string report,
            string label1, string description1, string label2, string description2, string label3, string description3)
        {
            var encounter = events.Find(x => x.id == ResearchEncounters.EventPrefix + subjectId);
            if (encounter == null || encounter.options == null || encounter.options.Length != 3)
                throw new InvalidOperationException("Missing rare skin encounter: " + subjectId);
            encounter.title = title;
            encounter.story = story;
            encounter.options[0].label = label1;
            encounter.options[0].description = description1;
            encounter.options[1].label = label2;
            encounter.options[1].description = description2;
            encounter.options[2].label = label3;
            encounter.options[2].description = description3;
            reports[subjectId] = RareSkinCatalog.NameForSubject(subjectId) + "에서 착안한 창작 조우. " + report;
        }
